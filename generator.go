const rosalineModule = "github.com/SeraphinaDX/Rosaline"
const rosalineVersion = "v0.17.0"
const generatedMarker = "Code generated by Rosaline Studio. DO NOT EDIT."

type generationReport struct {
	Created []string
	Updated []string
	Kept    []string
}

type generatedField struct {
	Name string
	Type string
}

type generationContext struct {
	fieldsByID  map[string]generatedField
	fields      []generatedField
	widgetsByID map[string]generatedField
	widgets     []generatedField
}

func generatedApplicationDirectory(designPath string) string {
	directory := filepath.Dir(designPath)
	filename := filepath.Base(designPath)
	name := strings.TrimSuffix(filename, filepath.Ext(filename))
	name = strings.TrimSpace(name)
	if name == "" || name == "." {
		name = "rosaline-app"
	}
	return filepath.Join(directory, name)
}

func generatedApplicationNeedsSetup(directory string) bool {
	for _, name := range []string{"go.mod", "go.sum", "ui_generated.go"} {
		if _, err := os.Stat(filepath.Join(directory, name)); err != nil {
			return true
		}
	}
	return false
}

func generateProject(project *designProject, directory string) (generationReport, error) {
	var report generationReport
	project.ensureComponentNames()
	if err := project.validate(); err != nil {
		return report, err
	}
	if strings.TrimSpace(directory) == "" {
		return report, fmt.Errorf("choose a project folder first")
	}
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return report, fmt.Errorf("create project folder: %w", err)
	}

	context := makeGenerationContext(project)
	generated := map[string]string{
		"ui_generated.go":     generatedUI(project, context),
		"state_generated.go":  generatedState(context),
		"events_generated.go": generatedEvents(project),
	}
	for name, contents := range generated {
		formatted, err := format.Source([]byte(contents))
		if err != nil {
			return report, fmt.Errorf("format %s: %w", name, err)
		}
		path := filepath.Join(directory, name)
		existed, err := replaceGeneratedFile(path, formatted)
		if err != nil {
			return report, fmt.Errorf("write %s: %w", name, err)
		}
		if existed {
			report.Updated = append(report.Updated, name)
		} else {
			report.Created = append(report.Created, name)
		}
	}
	createdAssets, updatedAssets, err := copyProjectAssets(project, directory)
	if err != nil {
		return report, err
	}
	report.Created = append(report.Created, createdAssets...)
	report.Updated = append(report.Updated, updatedAssets...)

	protected := map[string]string{
		"go.mod":      generatedGoMod(project),
		"main.go":     generatedMain(),
		"handlers.go": generatedHandlers(),
		"README.md":   generatedReadme(project),
	}
	for name, contents := range protected {
		path := filepath.Join(directory, name)
		if _, err := os.Stat(path); err == nil {
			report.Kept = append(report.Kept, name)
			continue
		} else if !os.IsNotExist(err) {
			return report, fmt.Errorf("inspect %s: %w", name, err)
		}
		if strings.HasSuffix(name, ".go") {
			formatted, err := format.Source([]byte(contents))
			if err != nil {
				return report, fmt.Errorf("format %s: %w", name, err)
			}
			contents = string(formatted)
		}
		if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
			return report, fmt.Errorf("write %s: %w", name, err)
		}
		report.Created = append(report.Created, name)
	}

	sort.Strings(report.Created)
	sort.Strings(report.Updated)
	sort.Strings(report.Kept)
	return report, nil
}

func replaceGeneratedFile(path string, contents []byte) (bool, error) {
	existing, err := os.ReadFile(path)
	if err == nil {
		if !strings.Contains(string(existing), generatedMarker) {
			return true, fmt.Errorf("refusing to replace an existing file without the Rosaline Studio generation marker")
		}
		return true, writeFileAtomically(path, contents, 0o644)
	}
	if !os.IsNotExist(err) {
		return false, err
	}
	return false, writeFileAtomically(path, contents, 0o644)
}

func writeFileAtomically(path string, contents []byte, permission os.FileMode) error {
	temporary, err := os.CreateTemp(filepath.Dir(path), ".rosaline-studio-*")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	defer func() {
		_ = temporary.Close()
		_ = os.Remove(temporaryPath)
	}()
	if err := temporary.Chmod(permission); err != nil {
		return err
	}
	if _, err := temporary.Write(contents); err != nil {
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(temporaryPath, path)
}

func makeGenerationContext(project *designProject) *generationContext {
	context := &generationContext{
		fieldsByID:  make(map[string]generatedField),
		widgetsByID: make(map[string]generatedField),
	}
	used := make(map[string]bool)
	var visit func(*designNode)
	visit = func(node *designNode) {
		if node == nil {
			return
		}
		fieldType := stateType(node.Kind)
		if fieldType != "" {
			base := exportedIdentifier(node.Name)
			if base == "" {
				base = exportedIdentifier(string(node.Kind))
			}
			name := uniqueGeneratedName(base, used)
			field := generatedField{Name: name, Type: fieldType}
			context.fieldsByID[node.ID] = field
			context.fields = append(context.fields, field)
		}
		widget := generatedField{Name: node.Component, Type: widgetType(node.Kind)}
		context.widgetsByID[node.ID] = widget
		context.widgets = append(context.widgets, widget)
		for _, child := range node.Children {
			visit(child)
		}
	}
	visit(project.Root)
	return context
}

func widgetType(kind widgetKind) string {
	switch kind {
	case kindColumn, kindRow:
		return "*rosaline.Box"
	case kindGrid:
		return "*rosaline.GridLayout"
	case kindStack:
		return "*rosaline.StackLayout"
	case kindCard:
		return "*rosaline.CardWidget"
	case kindScroll:
		return "*rosaline.ScrollWidget"
	case kindLabel:
		return "*rosaline.LabelWidget"
	case kindImage:
		return "*rosaline.ImageWidget"
	case kindButton:
		return "*rosaline.ButtonWidget"
	case kindTextBox:
		return "*rosaline.TextBoxWidget"
	case kindTextArea:
		return "*rosaline.TextAreaWidget"
	case kindCheckBox:
		return "*rosaline.CheckBoxWidget"
	case kindComboBox:
		return "*rosaline.ComboBoxWidget"
	case kindSlider:
		return "*rosaline.SliderWidget"
	case kindProgressBar:
		return "*rosaline.ProgressBarWidget"
	default:
		return "rosaline.Widget"
	}
}

func stateType(kind widgetKind) string {
	switch kind {
	case kindTextBox, kindTextArea, kindComboBox:
		return "string"
	case kindCheckBox:
		return "bool"
	case kindSlider, kindProgressBar:
		return "float64"
	default:
		return ""
	}
}

func exportedIdentifier(value string) string {
	words := strings.FieldsFunc(value, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	var builder strings.Builder
	for _, word := range words {
		if word == "" {
			continue
		}
		runes := []rune(word)
		runes[0] = unicode.ToUpper(runes[0])
		builder.WriteString(string(runes))
	}
	result := builder.String()
	if result == "" || unicode.IsDigit([]rune(result)[0]) {
		return "Value"
	}
	return result
}

func generatedUI(project *designProject, context *generationContext) string {
	imports := fmt.Sprintf("import rosaline %q\n", rosalineModule)
	assetSupport := ""
	if len(projectAssets(project)) != 0 {
		imports = fmt.Sprintf("import (\n\t\"embed\"\n\n\trosaline %q\n)\n", rosalineModule)
		assetSupport = `//go:embed assets/*
var generatedAssets embed.FS

func generatedPicture(name string) *rosaline.Picture {
	picture, err := rosaline.LoadImageFS(generatedAssets, "assets/"+name)
	if err != nil {
		return nil
	}
	return picture
}

`
	}
	return fmt.Sprintf(`// %s
package main

%s
%s
func runGeneratedApplication(app *Application) {
	rosaline.RunApp(rosaline.App{
		Title: %q,
		Width: %d,
		Height: %d,
		Padding: %d,
		Theme: studioTheme(),
		Content: buildUI(app),
	})
}

func buildUI(app *Application) rosaline.Widget {
	generatedWidgets = UIWidgets{}
	return %s
}

var generatedWidgets UIWidgets

// Widgets returns the controls created by the visual designer. Event handlers
// can use these references to update the interface directly.
func (app *Application) Widgets() *UIWidgets { return &generatedWidgets }

func rememberWidget[T rosaline.Widget](slot *T, widget T) T {
	*slot = widget
	return widget
}

%s
`, generatedMarker, imports, assetSupport, project.Title, max(320, project.Width), max(240, project.Height), max(0, project.Padding), generateNode(project.Root, context, 1), generatedTheme(project.Theme))
}

func generatedState(context *generationContext) string {
	var fields strings.Builder
	for _, field := range context.fields {
		fmt.Fprintf(&fields, "\t%s %s\n", field.Name, field.Type)
	}
	var widgets strings.Builder
	for _, field := range context.widgets {
		fmt.Fprintf(&widgets, "\t%s %s\n", field.Name, field.Type)
	}
	return fmt.Sprintf(`// %s
package main

import rosaline %q

// UIState contains values bound to generated Rosaline controls.
type UIState struct {
%s}

// UIWidgets contains direct references to every visually designed component.
type UIWidgets struct {
%s}
`, generatedMarker, rosalineModule, fields.String(), widgets.String())
}

func generatedEvents(project *designProject) string {
	handlers := referencedHandlers(project)
	if len(handlers) == 0 {
		return fmt.Sprintf("// %s\npackage main\n", generatedMarker)
	}
	var methods strings.Builder
	for _, name := range handlers {
		body := strings.TrimSpace(project.Handlers[name])
		if body == "" {
			body = "// Add your event code in Rosaline Studio."
		}
		fmt.Fprintf(&methods, "func (app *Application) %s() {\n%s\n}\n\n", name, indentBody(body, "\t"))
	}
	return fmt.Sprintf(`// %s
package main

import rosaline %q

var _ = rosaline.Message

%s`, generatedMarker, rosalineModule, methods.String())
}

func referencedHandlers(project *designProject) []string {
	seen := make(map[string]bool)
	var visit func(*designNode)
	visit = func(node *designNode) {
		if node == nil {
			return
		}
		for _, handler := range node.Events {
			if handler = strings.TrimSpace(handler); handler != "" {
				seen[handler] = true
			}
		}
		for _, child := range node.Children {
			visit(child)
		}
	}
	if project != nil {
		visit(project.Root)
	}
	result := make([]string, 0, len(seen))
	for name := range seen {
		result = append(result, name)
	}
	sort.Strings(result)
	return result
}

func indentBody(body, prefix string) string {
	lines := strings.Split(body, "\n")
	for index, line := range lines {
		if strings.TrimSpace(line) != "" {
			lines[index] = prefix + line
		}
	}
	return strings.Join(lines, "\n")
}

