func generateNode(node *designNode, context *generationContext, depth int) string {
	if node == nil {
		return "rosaline.Spacer(0, 0)"
	}
	indent := strings.Repeat("\t", depth)
	childIndent := strings.Repeat("\t", depth+1)
	children := func() string {
		if len(node.Children) == 0 {
			return ""
		}
		parts := make([]string, 0, len(node.Children))
		for _, child := range node.Children {
			parts = append(parts, childIndent+generateNode(child, context, depth+1))
		}
		return "\n" + strings.Join(parts, ",\n") + ",\n" + indent
	}
	oneChild := func() string {
		if len(node.Children) == 0 {
			return "rosaline.Spacer(0, 0)"
		}
		return generateNode(node.Children[0], context, depth+1)
	}

	var expression string
	switch node.Kind {
	case kindColumn:
		expression = "rosaline.Column(" + children() + ")" + layoutModifiers(node)
	case kindRow:
		expression = "rosaline.Row(" + children() + ")" + layoutModifiers(node)
	case kindGrid:
		childList := children()
		if childList == "" {
			expression = fmt.Sprintf("rosaline.Grid(%d)", max(1, node.Columns))
		} else {
			expression = fmt.Sprintf("rosaline.Grid(%d,%s)", max(1, node.Columns), childList)
		}
		expression += layoutModifiers(node)
	case kindStack:
		expression = "rosaline.Stack(" + children() + ")"
		if node.Expand {
			expression += ".Expand()"
		}
	case kindCard:
		expression = fmt.Sprintf("rosaline.Card(%s).Padding(%d)", oneChild(), max(0, node.Padding))
		if node.Expand {
			expression += ".Expand()"
		}
	case kindScroll:
		expression = "rosaline.Scroll(" + oneChild() + ")"
		if node.Width > 0 && node.Height > 0 {
			expression += fmt.Sprintf(".Size(%d, %d)", node.Width, node.Height)
		}
		if node.Expand {
			expression += ".Expand()"
		}
	case kindLabel:
		expression = fmt.Sprintf("rosaline.Label(%q)", node.Text)
		if node.Bold {
			expression += ".Bold()"
		}
	case kindImage:
		picture := "nil"
		if node.Asset != "" {
			picture = fmt.Sprintf("generatedPicture(%q)", node.Asset)
		}
		expression = fmt.Sprintf("rosaline.Image(%s).Placeholder(%q)", picture, defaultText(node.Text, "Choose an image"))
		if node.Width > 0 && node.Height > 0 {
			expression += fmt.Sprintf(".Fit(%d, %d)", node.Width, node.Height)
		}
		expression += generatedEventModifier(node, eventClick, "")
		if node.Expand {
			expression += ".Expand()"
		}
	case kindButton:
		if handler := eventHandler(node, eventClick); handler != "" {
			expression = fmt.Sprintf("rosaline.Button(%q, func() { app.%s() })", node.Text, handler)
		} else {
			expression = fmt.Sprintf("rosaline.Button(%q, nil)", node.Text)
		}
		if node.Primary {
			expression += ".Primary()"
		}
	case kindTextBox:
		field := context.fieldsByID[node.ID]
		expression = fmt.Sprintf("rosaline.TextBox(&app.State.%s)", field.Name)
		if node.Text != "" {
			expression += fmt.Sprintf(".Placeholder(%q)", node.Text)
		}
		if node.Password {
			expression += ".Password()"
		}
		expression += generatedEventModifier(node, eventChange, "string")
		expression += generatedEventModifier(node, eventSubmit, "string")
	case kindTextArea:
		field := context.fieldsByID[node.ID]
		expression = fmt.Sprintf("rosaline.TextArea(&app.State.%s)", field.Name)
		if node.Expand {
			expression += ".Expand()"
		}
		expression += generatedEventModifier(node, eventChange, "string")
	case kindCheckBox:
		field := context.fieldsByID[node.ID]
		expression = fmt.Sprintf("rosaline.CheckBox(%q, &app.State.%s)", node.Text, field.Name)
		expression += generatedEventModifier(node, eventChange, "bool")
	case kindComboBox:
		field := context.fieldsByID[node.ID]
		options := make([]string, 0, len(node.Options))
		for _, option := range node.Options {
			options = append(options, strconv.Quote(option))
		}
		expression = fmt.Sprintf("rosaline.ComboBox(&app.State.%s", field.Name)
		if len(options) != 0 {
			expression += ", " + strings.Join(options, ", ")
		}
		expression += ")"
		expression += generatedEventModifier(node, eventChange, "string")
	case kindSlider:
		field := context.fieldsByID[node.ID]
		minimum, maximum := node.Minimum, node.Maximum
		if maximum <= minimum {
			maximum = minimum + 100
		}
		expression = fmt.Sprintf("rosaline.Slider(&app.State.%s, %s, %s)", field.Name, numberLiteral(minimum), numberLiteral(maximum))
		if node.Step > 0 {
			expression += fmt.Sprintf(".Step(%s)", numberLiteral(node.Step))
		}
		if node.Vertical {
			expression += ".Vertical()"
		}
		expression += generatedEventModifier(node, eventChange, "float64")
	case kindProgressBar:
		field := context.fieldsByID[node.ID]
		expression = fmt.Sprintf("rosaline.ProgressBar(&app.State.%s)", field.Name)
		if node.Maximum > 0 && node.Maximum != 100 {
			expression += fmt.Sprintf(".Maximum(%s)", numberLiteral(node.Maximum))
		}
		if node.Vertical {
			expression += ".Vertical()"
		}
	case kindSpacer:
		expression = fmt.Sprintf("rosaline.Spacer(%d, %d)", max(0, node.Width), max(0, node.Height))
	default:
		expression = "rosaline.Label(\"Unknown widget\")"
	}

	if node.Kind != kindScroll && node.Kind != kindSpacer && node.Kind != kindImage && node.Width > 0 && node.Height > 0 {
		size := fmt.Sprintf("rosaline.Size(%%s, %d, %d)", node.Width, node.Height)
		field := context.widgetsByID[node.ID]
		expression = fmt.Sprintf(size, fmt.Sprintf("rememberWidget(&generatedWidgets.%s, %s)", field.Name, expression))
		return expression
	}
	field := context.widgetsByID[node.ID]
	expression = fmt.Sprintf("rememberWidget(&generatedWidgets.%s, %s)", field.Name, expression)
	return expression
}

func generatedEventModifier(node *designNode, event, valueType string) string {
	handler := eventHandler(node, event)
	if handler == "" {
		return ""
	}
	parameter := ""
	if valueType != "" {
		parameter = valueType
	}
	return fmt.Sprintf(".%s(func(%s) { app.%s() })", event, parameter, handler)
}

func layoutModifiers(node *designNode) string {
	result := fmt.Sprintf(".Gap(%d).Padding(%d)", max(0, node.Gap), max(0, node.Padding))
	if node.Expand {
		result += ".Expand()"
	}
	return result
}

func numberLiteral(value float64) string {
	return strconv.FormatFloat(value, 'f', -1, 64)
}
